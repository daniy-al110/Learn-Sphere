------------------------------------------------------------
-- ADMINS TABLE
------------------------------------------------------------
CREATE TABLE admins (
    admin_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    email VARCHAR2(100) UNIQUE NOT NULL,
    password VARCHAR2(100) NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

------------------------------------------------------------
-- TEACHERS TABLE
------------------------------------------------------------
CREATE TABLE teachers (
    teacher_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    name VARCHAR2(100) NOT NULL,
    email VARCHAR2(100) UNIQUE NOT NULL,
    password VARCHAR2(100) NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

------------------------------------------------------------
-- STUDENTS TABLE
------------------------------------------------------------
CREATE TABLE students (
    student_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    name VARCHAR2(100) NOT NULL,
    email VARCHAR2(100) UNIQUE NOT NULL,
    password VARCHAR2(100) NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

------------------------------------------------------------
-- COURSES TABLE
------------------------------------------------------------
CREATE TABLE courses (
    course_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    course_name VARCHAR2(200) NOT NULL,
    description VARCHAR2(500),
    teacher_id NUMBER,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_courses_teacher FOREIGN KEY (teacher_id)
        REFERENCES teachers (teacher_id)
        ON DELETE CASCADE
);

------------------------------------------------------------
-- ENROLLMENTS TABLE
------------------------------------------------------------
CREATE TABLE enrollments (
    enrollment_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    student_id NUMBER,
    course_id NUMBER,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_enroll_student FOREIGN KEY (student_id)
        REFERENCES students (student_id)
        ON DELETE CASCADE,
    CONSTRAINT fk_enroll_course FOREIGN KEY (course_id)
        REFERENCES courses (course_id)
        ON DELETE CASCADE
);

------------------------------------------------------------
-- ATTENDANCE TABLE
------------------------------------------------------------
CREATE TABLE attendance (
    attendance_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    student_id NUMBER,
    course_id NUMBER,
    attendance_date DATE NOT NULL,
    status VARCHAR2(10) CHECK (status IN ('present', 'absent')),
    CONSTRAINT fk_attend_student FOREIGN KEY (student_id)
        REFERENCES students (student_id),
    CONSTRAINT fk_attend_course FOREIGN KEY (course_id)
        REFERENCES courses (course_id)
);

------------------------------------------------------------
-- QUIZZES TABLE
------------------------------------------------------------
CREATE TABLE quizzes (
    quiz_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    course_id NUMBER,
    title VARCHAR2(200) NOT NULL,
    description VARCHAR2(500),
    time_limit NUMBER,
    is_active NUMBER(1) DEFAULT 0 CHECK (is_active IN (0,1)),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_quiz_course FOREIGN KEY (course_id)
        REFERENCES courses (course_id)
);

------------------------------------------------------------
-- QUIZ QUESTIONS TABLE
------------------------------------------------------------
CREATE TABLE quiz_questions (
    question_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    quiz_id NUMBER,
    question_text VARCHAR2(1000) NOT NULL,
    options CLOB NOT NULL,
    correct_answer VARCHAR2(500) NOT NULL,
    points NUMBER DEFAULT 1,
    CONSTRAINT fk_qq_quiz FOREIGN KEY (quiz_id)
        REFERENCES quizzes (quiz_id)
);

------------------------------------------------------------
-- QUIZ RESPONSES TABLE
------------------------------------------------------------
CREATE TABLE quiz_responses (
    response_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    quiz_id NUMBER,
    student_id NUMBER,
    answers CLOB NOT NULL,
    score NUMBER,
    submitted_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_qr_quiz FOREIGN KEY (quiz_id)
        REFERENCES quizzes (quiz_id),
    CONSTRAINT fk_qr_student FOREIGN KEY (student_id)
        REFERENCES students (student_id)
);

------------------------------------------------------------
-- ASSIGNMENTS TABLE
------------------------------------------------------------
CREATE TABLE assignments (
    assignment_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    course_id NUMBER,
    title VARCHAR2(200) NOT NULL,
    description VARCHAR2(1000),
    link VARCHAR2(500),
    due_date DATE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_assign_course FOREIGN KEY (course_id)
        REFERENCES courses (course_id)
);

------------------------------------------------------------
-- ASSIGNMENT SUBMISSIONS TABLE
------------------------------------------------------------
CREATE TABLE assignment_submissions (
    submission_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    assignment_id NUMBER,
    student_id NUMBER,
    marks NUMBER,
    submitted_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_sub_assign FOREIGN KEY (assignment_id)
        REFERENCES assignments (assignment_id),
    CONSTRAINT fk_sub_student FOREIGN KEY (student_id)
        REFERENCES students (student_id)
);

------------------------------------------------------------
-- FEEDBACK TABLE
------------------------------------------------------------
CREATE TABLE feedback (
    feedback_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    student_id NUMBER,
    course_id NUMBER,
    teacher_id NUMBER,
    rating NUMBER CHECK (rating BETWEEN 1 AND 5),
    review VARCHAR2(1000),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_feedback_student FOREIGN KEY (student_id)
        REFERENCES students (student_id)
        ON DELETE CASCADE,
    CONSTRAINT fk_feedback_course FOREIGN KEY (course_id)
        REFERENCES courses (course_id)
        ON DELETE CASCADE,
    CONSTRAINT fk_feedback_teacher FOREIGN KEY (teacher_id)
        REFERENCES teachers (teacher_id)
        ON DELETE CASCADE
);